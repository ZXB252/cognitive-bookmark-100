function ideaAnalysis(book, profile) {
  return expandedIdeas(book, profile).map((idea, index) => {
    const detail = explainIdea(idea, book, profile, index);
    return {
      title: detail.title,
      idea,
      meaning: detail.meaning,
      action: detail.action,
      warning: detail.warning
    };
  });
}

function hasAny(text, words) {
  return words.some((word) => text.includes(word));
}

