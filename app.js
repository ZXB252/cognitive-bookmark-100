const memoryStore = {};

function readStore(key, fallback) {
  try {
    return JSON.parse(localStorage.getItem(key) || fallback);
  } catch (error) {
    return JSON.parse(memoryStore[key] || fallback);
  }
}

function writeStore(key, value) {
  const text = JSON.stringify(value);
  memoryStore[key] = text;
  try {
    localStorage.setItem(key, text);
  } catch (error) {
    // Some file:// or private browsing contexts block localStorage.
  }
}

const state = {
  filter: "all",
  query: "",
  selectedId: null,
  done: readStore("cog-bookmark-done", "{}"),
  notes: readStore("cog-bookmark-notes", "{}")
};

const $ = (id) => document.getElementById(id);
const todayKey = () => new Date().toISOString().slice(0, 10);
const bookId = (book) => `${book.t}-${book.a}`;

function save() {
  writeStore("cog-bookmark-done", state.done);
  writeStore("cog-bookmark-notes", state.notes);
}

function todayBook() {
  const start = new Date("2026-01-01T00:00:00");
  const diff = Math.floor((new Date() - start) / 86400000);
  return books[((diff % books.length) + books.length) % books.length];
}

function streak() {
  const dates = new Set(Object.values(state.done).map((entry) => entry.date));
  let count = 0;
  const cursor = new Date();
  while (dates.has(cursor.toISOString().slice(0, 10))) {
    count += 1;
    cursor.setDate(cursor.getDate() - 1);
  }
  return count;
}

function updateStats() {
  const doneCount = Object.keys(state.done).length;
  $("doneCount").textContent = doneCount;
  $("streakCount").textContent = streak();
  $("progressPct").textContent = `${Math.round((doneCount / books.length) * 100)}%`;
}

function renderToday() {
  const book = todayBook();
  $("todayTitle").textContent = book.t;
  $("todayMeta").textContent = `${book.a} · ${book.c} · ${book.i[0]}`;
  $("todayButton").onclick = () => openBook(bookId(book));
}

function visibleBooks() {
  const q = state.query.trim().toLowerCase();
  return books.filter((book) => {
    const id = bookId(book);
    const isDone = Boolean(state.done[id]);
    const filterPass = state.filter === "all" || (state.filter === "done" ? isDone : !isDone);
    const text = [book.t, book.a, book.c, ...book.i, book.e, book.p].join(" ").toLowerCase();
    return filterPass && (!q || text.includes(q));
  });
}

