function renderBooks() {
  const list = $("bookList");
  const data = visibleBooks();
  list.innerHTML = "";

  if (!data.length) {
    const empty = document.createElement("article");
    empty.className = "book-card";
    empty.innerHTML = "<h2>没有匹配的书</h2><p class='idea-preview'>换个关键词，或者切回全部看看。</p>";
    list.appendChild(empty);
    return;
  }

  data.forEach((book, index) => {
    const id = bookId(book);
    const done = Boolean(state.done[id]);
    const card = document.createElement("article");
    card.className = `book-card${done ? " done" : ""}`;
    card.innerHTML = `
      <div class="book-topline">
        <span class="badge">${books.indexOf(book) + 1} · ${book.c}</span>
        <span class="checkmark">${done ? "已打卡" : ""}</span>
      </div>
      <h2>${book.t}</h2>
      <p class="book-author">${book.a}</p>
      <p class="idea-preview">${book.i[0]}</p>
      <div class="card-actions">
        <button class="ghost-btn" type="button" data-open="${id}">看观点</button>
        <button class="primary-btn ${done ? "done" : ""}" type="button" data-check="${id}">${done ? "更新笔记" : "打卡"}</button>
      </div>
    `;
    card.style.animationDelay = `${Math.min(index * 18, 220)}ms`;
    list.appendChild(card);
  });
}

function openBook(id) {
  const book = books.find((item) => bookId(item) === id);
  if (!book) return;
  const profile = profileFor(book);
  state.selectedId = id;
  $("dialogCategory").textContent = book.c;
  $("dialogTitle").textContent = book.t;
  $("dialogAuthor").textContent = book.a;
  $("dialogModel").textContent = profile.model;
  $("dialogUseCase").textContent = profile.use;
  $("dialogIdeas").innerHTML = expandedIdeas(book, profile).map((idea) => `<li>${idea}</li>`).join("");
  $("dialogAnalysis").innerHTML = ideaAnalysis(book, profile).map((item) => `
    <article class="analysis-card">
      <strong>${item.title}</strong>
      <p>${item.idea}</p>
      <dl>
        <dt>怎么理解</dt><dd>${renderPoints(item.meaning)}</dd>
        <dt>今天怎么用</dt><dd>${renderPoints(item.action)}</dd>
        <dt>注意别误会</dt><dd>${renderPoints(item.warning)}</dd>
      </dl>
    </article>
  `).join("");
  $("dialogCounter").textContent = profile.counter;
  $("dialogExample").textContent = book.e;
  $("dialogCase").innerHTML = caseSimulation(book, profile).map((item) => `
    <div>
      <span>${item.label}</span>
      <p>${item.text}</p>
    </div>
  `).join("");
  $("dialogMatrix").innerHTML = transferMatrix(book, profile).map((item) => `
    <article>
      <strong>${item.area}</strong>
      <p>${item.q}</p>
      <em>${item.a}</em>
    </article>
  `).join("");
  $("dialogReading").innerHTML = readingPlan(book, profile).map((step) => `<li>${step}</li>`).join("");
  $("dialogTrap").textContent = profile.trap;
  $("dialogQuiz").innerHTML = quizItems(book, profile).map((item) => `
    <details>
      <summary>${item.q}</summary>
      <p>${item.hint}</p>
    </details>
  `).join("");
  $("dialogTemplate").innerHTML = outputTemplate(book, profile).map((line) => `<p>${line}</p>`).join("");
  $("dialogPrompt").textContent = book.p;
  $("noteInput").value = state.notes[id] || "";
  $("checkButton").textContent = state.done[id] ? "更新打卡" : "完成打卡";
  $("checkButton").classList.toggle("done", Boolean(state.done[id]));
  $("bookDialog").showModal();
}

function checkSelected() {
  if (!state.selectedId) return;
  state.done[state.selectedId] = { date: todayKey(), at: new Date().toISOString() };
  state.notes[state.selectedId] = $("noteInput").value.trim();
  save();
  $("bookDialog").close();
  updateStats();
  renderBooks();
  renderToday();
}

function bind() {
  $("searchInput").addEventListener("input", (event) => {
    state.query = event.target.value;
    renderBooks();
  });

  document.querySelectorAll(".segmented button").forEach((button) => {
    button.addEventListener("click", () => {
      document.querySelector(".segmented button.active").classList.remove("active");
      button.classList.add("active");
      state.filter = button.dataset.filter;
      renderBooks();
    });
  });

  document.addEventListener("click", (event) => {
    const openId = event.target.dataset.open || event.target.dataset.check;
    if (openId) openBook(openId);
  });

  $("closeDialog").addEventListener("click", () => $("bookDialog").close());
  $("checkButton").addEventListener("click", checkSelected);
}

if (location.protocol !== "file:" && "serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("./sw.js").catch(() => {});
  });
}

function showFatal(error) {
  const list = $("bookList");
  if (!list) return;
  list.innerHTML = `
    <article class="book-card">
      <h2>书架加载遇到问题</h2>
      <p class="idea-preview">${error.message || error}</p>
    </article>
  `;
}

try {
  bind();
  updateStats();
  renderToday();
  renderBooks();
} catch (error) {
  showFatal(error);
  throw error;
}
